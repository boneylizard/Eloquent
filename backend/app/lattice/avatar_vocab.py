def vocab_list_to_prompt_block(list_name, items):
    joining = ", ".join(items)
    return f"{list_name}: {joining}"


def build_vocab_prompt_block():
    lines = []
    for key in AVATAR_FIELD_KEYS:
        items = VOCAB_BY_FIELD[key]
        label = key.upper()
        lines.append(vocab_list_to_prompt_block(label, items))
    return "\n\n".join(lines)


def build_avatar_prompt(avatar_data):
    fields = {k: "" for k in AVATAR_FIELD_KEYS}
    if avatar_data:
        for key in AVATAR_FIELD_KEYS:
            val = avatar_data.get(key, "")
            if isinstance(val, (int, float)):
                val = str(val)
            fields[key] = val or ""
    try:
        return AVATAR_PROMPT_TEMPLATE.format(**fields)
    except KeyError:
        return AVATAR_PROMPT_TEMPLATE


def validate_avatar_selections(avatar_data):
    errors = []
    if not avatar_data:
        return ["Avatar data is missing"]
    for key in AVATAR_FIELD_KEYS:
        val = avatar_data.get(key, "")
        if not val or (isinstance(val, str) and not val.strip()):
            errors.append(f"Missing selection for {key}")
    return errors


def get_avatar_field_names():
    return list(AVATAR_FIELD_KEYS)
